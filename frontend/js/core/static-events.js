  const events = ["change", "click", "focus", "input", "keydown", "submit"];
  const bound = new WeakMap();
  function bindElement(element) {
    let attached = bound.get(element);
    if (!attached) { attached = new Set(); bound.set(element, attached); }
    events.forEach(function (type) {
      const id = element.getAttribute('data-static-on' + type);
      if (!Object.prototype.hasOwnProperty.call(handlers, id) || attached.has(type)) return;
      attached.add(type);
      element.addEventListener(type, function (event) {
        if (handlers[id].call(this, event) === false) event.preventDefault();
      });
    });
  }
  const selector = events.map(function (type) { return '[data-static-on' + type + ']'; }).join(',');
  function bindTree(root) {
    if (root.nodeType === 1 && root.matches(selector)) bindElement(root);
    if (root.querySelectorAll) root.querySelectorAll(selector).forEach(bindElement);
  }
  // A connected clone can be clicked synchronously before the observer runs.
  // Bind along its path during capture; callbacks still run on their elements.
  events.forEach(function (type) {
    document.addEventListener(type, function (event) {
      for (let element = event.target; element && element !== document; element = element.parentNode) {
        if (element.nodeType === 1 && element.matches(selector)) bindElement(element);
      }
    }, true);
  });
  // Also bind cloned static controls, keeping element-level propagation semantics.
  new MutationObserver(function (records) {
    records.forEach(function (record) {
      record.addedNodes.forEach(bindTree);
    });
  }).observe(document.documentElement, { childList: true, subtree: true });
  document.addEventListener('DOMContentLoaded', function () { bindTree(document); }, { once: true });
