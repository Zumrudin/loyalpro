// Раскладывает пары «вопрос клиента → ответ клиники» по услугам (по ключевым словам).
// Запуск: node scripts/build-qa-pairs.js && node scripts/classify-qa-by-service.js
const fs = require('fs');
const path = require('path');
const EX = path.join(__dirname, '..', '..', 'exports');
const pairs = require(path.join(EX, 'qa_pairs.json'));
const dialogs = require(path.join(EX, 'chat_history_dialogs.json'));
const clientKeys = new Set(dialogs.filter((d) => d.dtype === 'клиент').map((d) => d.key));

const SERVICES = [
  ['Лазерная эпиляция', /эпиляц|лазер(?!н\w* омол)|бикини|подмышк|ног[иа]х? |голен|депиляц|александрит|диод/i],
  ['Ботулинотерапия (ботокс)', /ботокс|ботулакс|ботулин|диспорт|ксеомин|морщин|миотокс|гипергидроз/i],
  ['Филлеры / контурная пластика / губы', /филлер|гиалурон|контурн|губ[аыуе]?\b|губы|скул|подбород|нос[оа]губ|ювидерм|стилаж|увеличени\w* губ/i],
  ['Биоревитализация / мезотерапия / биорепарация', /биоревитал|ревитал|мезотерап|биорепар|профайло|полинуклеотид|plinest|ревиголд|revi|skinbooster|скинбустер|гиалуронов\w* кислот/i],
  ['Плазмолифтинг / PRP', /плазмолифт|prp|плазма/i],
  ['Чистка / пилинг / уход за лицом', /чистк|пилинг|пилинг|карбокс|гидрафейшл|hydrafacial|уход за лиц|маск[аи]\b|ретинол|акне|пост-?акне|прыщ/i],
  ['Аппаратная косметология (RF, ультразвук, лифтинг)', /rf-?лифт|рф-?лифт|ультразвук|smas|смас|ультраформ|ulthera|микроигл|фракцион|термаж|лифтинг|hifu|хифу|аппаратн/i],
  ['Нитевой лифтинг / мезонити', /нит[ие]|мезонит|аптос/i],
  ['Удаление новообразований / сосудов / татуажа', /удален\w* (?:родим|папилл|бородав|кондилом|сосуд|тату|татуаж)|родинк|папиллом|бородавк|сосудист|купероз|звездочк|татуаж|перманент/i],
  ['Коррекция фигуры / массаж / LPG / прессотерапия', /массаж|lpg|лпж|прессотерап|обёртыван|обертыван|целлюлит|похуден|кавитац|миостимул/i],
  ['Трихология / волосы', /волос[аы]?\b|трихолог|выпадени|мезотерап\w* (?:волос|головы)|плазм\w* (?:волос|головы)|кожа головы/i],
  ['Консультация врача / диагностика', /консультаци|приём врача|прием врача|осмотр|диагностик|врач-/i],
  ['Косметика / домашний уход / товары', /крем|сыворотк|косметик|продаж\w* (?:у вас|ли)|купить|гель для|тоник|средств[оа] (?:для|по уходу)/i],
  ['Сертификаты / абонементы / бонусы / акции', /сертификат|абонемент|бонус|кэшбэк|кешбэк|скидк|акци[яию]|карт[аыу] лояльн|баллы?\b/i],
  ['Справки / налоговый вычет / документы', /справк|вычет|договор|лицензи|чек\b|документ/i],
];
const GENERAL = [
  ['Запись / перенос / отмена / график', /запис|окошк|свободн|перенес|перенос|отмен|во сколько|график|когда принима|на (?:завтра|сегодня|пятниц|суббот|понедельн|вторник|сред|четверг|воскресень)/i],
  ['Цена / стоимость', /сколько стоит|стоимост|цена|цены|прайс|почём|почем/i],
  ['Адрес / как добраться / парковка', /адрес|где наход|как добраться|парковк|метро|подъезд|вход/i],
];

const out = {};
const add = (k, p) => (out[k] ||= []).push(p);
let used = 0;
for (const p of pairs) {
  if (!clientKeys.has(p.dialog)) continue;
  used++;
  const text = p.q;
  const hits = SERVICES.filter(([, re]) => re.test(text)).map(([n]) => n);
  if (hits.length) hits.forEach((h) => add(h, p));
  else {
    const g = GENERAL.find(([, re]) => re.test(text));
    add(g ? 'Общие: ' + g[0] : 'Прочее / без темы', p);
  }
}
const stat = Object.entries(out).map(([k, v]) => [k, v.length]).sort((a, b) => b[1] - a[1]);
for (const [k, v] of Object.entries(out)) {
  const f = path.join(EX, 'by_service', k.replace(/[^\wа-яё]+/gi, '_') + '.txt');
  fs.writeFileSync(f, v.map((p, i) => `#${i + 1} [${p.when}] К: ${p.q}\nА(${p.a_role}): ${p.a}`).join('\n\n'));
}
console.log('клиентских пар:', used, 'из', pairs.length);
stat.forEach(([k, n]) => console.log(String(n).padStart(5), k));
