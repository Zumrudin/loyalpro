async function checkCatalog(salonId) {
  const { ycGetServiceCatalog } = require('../services/yclients');
  const salon = await db.oneOrNone(
    `SELECT id, yclients_company_id, yclients_partner_token, yclients_user_token
       FROM salons WHERE id=$1`, [salonId]);
  if (!salon) return null;
  const staff = await db.any(
    `SELECT yclients_staff_id FROM staff_members WHERE salon_id=$1 AND is_active=true`, [salonId]);
  const { priced, categories } = await ycGetServiceCatalog(salon, staff.map(s => s.yclients_staff_id));
  const svcIds = new Set(priced.map(s => String(s.id)));
  const catIds = new Set(categories.map(c => String(c.id)));
  for (const p of PROGRAMS) {
    for (const item of p.conditions.items) {
      const known = item.type === 'category' ? catIds : svcIds;
      const missing = item.ids.filter(id => !known.has(String(id)));
      if (missing.length) console.log(`  ! «${p.title}»: нет в каталоге (${item.type}): ${missing.join(', ')}`);
      else console.log(`  ✓ «${p.title}»: все ${item.ids.length} ${item.type} на месте`);
    }
  }
  return true;
}

