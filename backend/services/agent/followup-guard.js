'use strict';
// ============================================================
// Напоминание о себе идёт БЕЗ инструментов: модель не видит ни слотов, ни
// каталога. Оставленная без данных, она начинает время СОЧИНЯТЬ — этот класс
// дефекта у проекта уже был (инцидент 2026-08-10, alien_time_attribution).
//
// Правило: время в напоминании законно, ТОЛЬКО если оно дословно звучало в
// прошлых репликах Милы. Нарушение → напоминание НЕ отправляется вовсе.
// Вырезать подстроку нельзя: фраза рвётся и пациент получает огрызок, а
// молчание безопаснее (тот же принцип, что fail-safe в care/decision.js).
//
// Юнит-тесты: agent-followup-guard.test.js
//
// ОСТАТОЧНЫЕ РИСКИ (как у соседних guard'ов — намеренно не устраняются):
// - Длительность, записанная как «1:30» (полтора часа), от времени 01:30
//   ничем не отличается: guard её тоже сочтёт временем и, не найдя точного
//   совпадения в прошлых репликах, погасит напоминание. Размен осознанный —
//   молчание дешевле, чем отправка выдуманного времени.
// - Guard проверяет ТОЛЬКО время суток и ничего не знает о ДАТЕ: законное
//   время, дословно звучавшее у прошлого дня записи, но привязанное в новом
//   тексте к ДРУГОЙ дате, он не поймает — совпадение чисел для него
//   достаточно.
// - Точечная форма (см. ниже) неоднозначна и для дат, где ПЕРВАЯ часть —
//   день больше 12 (например, «20.08» = 20 августа): правило «хотя бы одна
//   часть больше 12» читает её как время 20:08, а не как дату. Эвристика
//   намеренно не разбирает семантику «день/месяц» — того же рода компромисс,
//   что и общее правило ниже.
// ============================================================

// Двоеточная форма: границы слева/справа — не \b, в JS он считает словом
// только ASCII, и на кириллице вокруг числа срабатывал бы непредсказуемо
// (та же готча, что в address-guard). Слева/справа не должно быть цифры или
// двоеточия — иначе «112:30» отдал бы «12:30», а «12:345» отдал бы «12:34».
// Двусмысленности с датой у двоеточной формы нет: «11:08» — всегда время.
const COLON_RE = /(?<![\d:])(\d{1,2}):(\d{2})(?![\d:])/g;

// Точечная форма («в 14.30», «встреча в 12.45»): по-русски время пишут и
// через точку, и модель это воспроизводит — до фикса такие пары guard'у были
// не видны вовсе, и выдуманное «14.30» ушло бы пациенту незамеченным
// (ложноОТРИЦАТЕЛЬНОЕ срабатывание, инцидент найден ревью 2026-08-12).
// Проблема в том, что та же запись «ДД.ММ» — обычная дата («11.08»), и
// добавить точку в общую регулярку нельзя не разведя их: «11.08» стало бы
// читаться как 11:08.
//
// Границы те же приёмы, что у двоеточной формы, НО лукахед справа блокирует
// только цифру — не точку: иначе точка конца предложения («в 21.00. Ждём»)
// рвала бы законный матч ровно там, где время написано верно.
const DOT_RE = /(?<![\d.])(\d{1,2})\.(\d{2})(?!\d)/g;

// 'HH:MM'/'HH.MM' → минуты суток. Через число, а не строку: '9:00' и
// '09:00' (а с фиксом — и '9.00') — одно и то же время, а строковое
// сравнение объявило бы второе выдумкой.
function toMinutes(h, m) {
  const hh = Number(h), mm = Number(m);
  if (!Number.isInteger(hh) || !Number.isInteger(mm) || hh > 23 || mm > 59) return null;
  return hh * 60 + mm;
}

// Разводит время и дату у точечной пары: обе части ≤ 12 читаются как ДЕНЬ и
// МЕСЯЦ (день у большинства обиходных дат в такой записи тоже не превышает
// 12 — «11.08», «3.05»), и двусмысленность разрешается В ПОЛЬЗУ ДАТЫ.
// Ошибиться в эту сторону безопаснее: guard просто не заметит эту пару и не
// добавит её ни в проверяемое время, ни в разрешённое — а не погасит
// законное напоминание из-за юбилейной даты в тексте. Если хотя бы одна
// часть больше 12 («14.30», «12.45») — датой это быть не может (в
// календаре нет ни 14-го месяца, ни дня/месяца «45»), и пара безусловно
// время.
function isDateLikeDotPair(hh, mm) {
  return hh <= 12 && mm <= 12;
}

// Единый проход по обеим нотациям в порядке появления в тексте — от этого
// зависит порядок elementов, который проверяет тест collectTimes(). Правило
// «≤12/≤12 → дата» применяется ТОЛЬКО к точечной форме; двоеточная форма
// всегда однозначна.
function extractCandidates(text) {
  if (typeof text !== 'string') return [];
  const out = [];
  for (const m of text.matchAll(COLON_RE)) {
    const minutes = toMinutes(m[1], m[2]);
    if (minutes !== null) out.push({ index: m.index, raw: m[0], minutes });
  }
  for (const m of text.matchAll(DOT_RE)) {
    const hh = Number(m[1]), mm = Number(m[2]);
    if (isDateLikeDotPair(hh, mm)) continue;
    const minutes = toMinutes(m[1], m[2]);
    if (minutes !== null) out.push({ index: m.index, raw: m[0], minutes });
  }
  out.sort((a, b) => a.index - b.index);
  return out;
}

/**
 * Все времена текста в исходном написании (порядок сохраняется), обе
 * нотации — «12:30» и «14.30». Не-строка на входе НЕ коэрсится (в проекте
 * это осознанно запрещённый приём — см. visit-rating.js/care/decision.js:
 * `String(['12:30'])` даёт `'12:30'`, то есть массив тихо притворяется
 * валидным текстом) — трактуется как «время не найдено».
 */
function collectTimes(text) {
  return extractCandidates(text).map((c) => c.raw);
}

function timeMinutesSet(text) {
  const set = new Set();
  for (const c of extractCandidates(text)) set.add(c.minutes);
  return set;
}

/**
 * Есть ли в тексте время, которого не было в прошлых репликах Милы.
 *
 * @param {string} text текст напоминания.
 *   Не-строка трактуется как «время выдумано» (`true`) — безопасно, ход
 *   просто не уйдёт пациенту, вместо того чтобы притвориться пустым текстом.
 * @param {string} priorAssistantText СКЛЕЕННЫЕ ПРОШЛЫЕ РЕПЛИКИ ТОЛЬКО САМОЙ
 *   МИЛЫ — без сообщений клиента и без реплик администратора (строк с
 *   маркером `OPERATOR_MARK` из `services/agent/history.js`, их обязан
 *   срезать вызывающий код). Модуль этого не проверяет и проверить не
 *   может: если сюда попадёт весь транскрипт целиком, время, названное
 *   САМИМ клиентом (или администратором), начнёт легализовать что угодно —
 *   guard молча превратится в no-op, и цена ошибки та же, что у пропуска
 *   всей проверки.
 *   Не-строка трактуется как «разрешённых времён нет» (пустой набор) —
 *   тоже безопасно: любое время в `text` в этом случае окажется вне
 *   разрешённого множества.
 */
function hasInventedTime(text, priorAssistantText) {
  if (typeof text !== 'string') return true;
  const allowed = timeMinutesSet(priorAssistantText);
  for (const min of timeMinutesSet(text)) {
    if (!allowed.has(min)) return true;
  }
  return false;
}

module.exports = { hasInventedTime, collectTimes };
