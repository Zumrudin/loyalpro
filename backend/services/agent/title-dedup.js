'use strict';

// ── «ДОЛЖНОСТЬ НАЗЫВАЙ ОДИН РАЗ ЗА ДИАЛОГ» — детерминированная дочистка. ─────
// Чистый модуль: ни БД, ни HTTP.
//
// Правило промпта: должность специалиста звучит при ПЕРВОМ упоминании, дальше —
// только имя («косметолог-эстетист Юлия… у косметолога-эстетиста Юлии…» подряд
// звучит казённо). Держалось только на промпте. Замена безопасна текстуально:
// в русской конструкции «должность + Имя» падеж несёт ИМЯ, поэтому срез
// должности («у косметолога-эстетиста Юлии» → «у Юлии») оставляет фразу
// грамматичной. Первое упоминание в ТЕКУЩЕЙ реплике не трогается — срезаются
// только имена, чья должность уже звучала в ПРОШЛЫХ репликах Милы.
//
// Должности — паттерны со склонением (списком, а не «любое слово перед именем»).
// «наш специалист» намеренно не в списке: это не должность, а оборот речи.
// Первая буква каждой должности — явным классом [Гг]/[Вв]/[Кк], а НЕ флагом `i`:
// с `iu` свойства \p{Lu}/\p{Ll} замыкаются по case-folding и капитализация имени
// перестаёт проверяться вовсе — «косметолог-эстетист свободна» захватывало бы
// «свободна» как имя.
//
// Пробелы вокруг дефиса обязательны: модель получает должность ДОСЛОВНО из
// staff_members.specialization, а там боевые написания «Косметолог- эстетист»
// (Гатауллина Юлия) и «Косметолог - эстетист» (Палий) — без этого допуска фича
// была бы no-op ровно для тех, ради кого писалась. ИЗВЕСТНЫЙ ПРОБЕЛ: должность
// без дефиса вовсе («Врач косметолог», Калмыкова) не покрыта — дефис в шаблоне
// обязателен. Лечится тем же приёмом (сделать дефис необязательным), но это
// расширение поверхности, а не правка дефекта: сегодня непокрытая должность
// значит лишь «повтор не срезан», то есть прежнее поведение.
//
// Разделители внутри должности и между должностью и именем — [^\S\n], а не \s:
// \s спанит перенос строки, и в вертикальном списке («Косметолог-эстетист\n
// Юлия — 12:00») пара склеивалась через строки и срезала заголовок списка.
const H = '[^\\S\\n]';         // пробел, но НЕ перенос строки
const POSITION_SRC =
  `(?:[Гг]лавн[а-яё]+${H}+[Вв]рач[а-яё]*`
  + `|[Вв]рач[а-яё]*${H}*-${H}*косметолог[а-яё]*`
  + `|[Кк]осметолог[а-яё]*${H}*-${H}*эстетист[а-яё]*)`;
// Пара «должность[,][ —-] Имя [Отчество]» — имя капитализировано, 1–2 слова.
// Тире в разделителе — с прода: «записала вас к главному врачу - Пери».
const PAIR_RE = new RegExp(
  `${POSITION_SRC},?${H}*[—-]?${H}+(\\p{Lu}\\p{Ll}+(?:${H}+\\p{Lu}\\p{Ll}+)?)`, 'gu');

// Имя в переписке склоняется («Юлия» / «к Юлии») — сверка по стему, тот же
// приём, что mentionsPerson в reply-guard.
const MIN_STEM = 4;
const stemOf = (word) => word.slice(0, Math.max(MIN_STEM, word.length - 2));

// Заглавное слово после должности — далеко не всегда имя: «Записаться к
// врачу-косметологу Вы можете на любой день» давало пару «Вы», а срез
// превращал следующую реплику в «К Вы можете прийти завтра» — то есть ломал
// предложение, а не убирал лишнее (это качественно хуже любого пропуска).
// Два фильтра: слово короче 4 букв именем не считаем вовсе (местоимения и
// союзы почти все короткие, а стем короче MIN_STEM всё равно неработоспособен)
// и явный стоп-список для длинных («Ваша», «Если», «Также»).
// ЦЕНА ФИЛЬТРА ДЛИНЫ: короткие настоящие имена («Ева», «Лия») не срезаются —
// это прежнее поведение (должность прозвучит второй раз), а не поломка текста.
const STOP_WORDS = new Set([
  'вы', 'вам', 'вас', 'ваш', 'ваша', 'ваше', 'ваши',
  'наш', 'наша', 'наше', 'наши', 'это', 'если', 'также', 'ещё', 'еще',
]);
const firstWord = (name) => String(name).split(/\s+/)[0];
const isNameWord = (word) => word.length >= MIN_STEM && !STOP_WORDS.has(word.toLowerCase());

// Точного равенства стемов МАЛО: у 4-буквенного имени стем — всё слово, и
// «Юлия»/«Юлии» разошлись бы последней буквой (склонение живёт в хвосте).
// Поэтому членство в seen проверяется общим префиксом: от КОРОТКОГО стема
// отрезаются ещё до 2 финальных букв, но не короче 3-х. Сравнение длин стоит
// ДО проверки равенства: без него любой 2–3-буквенный захват совпадал бы сам с
// собой и проезжал мимо фильтров выше.
// ИЗВЕСТНАЯ КОЛЛИЗИЯ (закреплена тестом, чинить молча не надо): имена с общими
// тремя буквами склеиваются — «Александра» и «Алексей» считаются одним
// человеком. Цена — лишний срез должности у второго мастера, то есть та же
// деградация «должность не прозвучала», а не искажение факта. Тот же
// остаточный риск у personRe в reply-guard.
function stemsMatch(a, b) {
  if (a.length < MIN_STEM || b.length < MIN_STEM) return false;
  if (a === b) return true;
  const n = Math.max(MIN_STEM - 1, Math.min(a.length, b.length) - 2);
  return a.slice(0, n) === b.slice(0, n);
}

// Стемы имён, у которых должность уже звучала в прошлом тексте Милы.
function namesWithTitle(priorAssistantText) {
  const out = new Set();
  for (const m of String(priorAssistantText || '').matchAll(PAIR_RE)) {
    const word = firstWord(m[1]);
    if (isNameWord(word)) out.add(stemOf(word));
  }
  return out;
}

// → { replies, stripped } — stripped идёт в лог оркестратора.
// PAIR_RE глобальный и общий для matchAll и replace — это безопасно: matchAll
// итерирует КЛОН регулярки, а replace с g-флагом сбрасывает lastIndex сам.
// Массив ВСЕГДА возвращается новый (slice на пути «резать нечего»): вызывающий
// делает replies.length = 0 + push(...titled.replies), и вернуть ему тот же
// объект значило бы очистить массив прямо перед раскладкой его же содержимого —
// пустая серия реплик, а её диспетчер трактует как отказ («передаю
// администратору»). Сегодня та ветка недостижима (stripped пуст), но цена
// ошибки несоразмерна экономии на одном slice.
function stripRepeatedTitles(replies, priorAssistantText) {
  const list = Array.isArray(replies) ? replies : [];
  const seen = namesWithTitle(priorAssistantText);
  if (!seen.size) return { replies: list.slice(), stripped: [] };
  const stripped = [];
  const out = list.map(text => String(text).replace(PAIR_RE, (full, name) => {
    const word = firstWord(name);
    if (!isNameWord(word)) return full;
    const stem = stemOf(word);
    if (![...seen].some(s => stemsMatch(s, stem))) return full;
    stripped.push(full.trim());
    return name;
  }));
  return { replies: out, stripped };
}

module.exports = { stripRepeatedTitles, namesWithTitle, stemsMatch };
