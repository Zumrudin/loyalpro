'use strict';

// ── Оценка визита («5» в ответ на автоопрос) без LLM-вызова. Чистый модуль. ──
//
// ЗАЧЕМ: инцидент 2026-08-10 (79776646672) — пациентка прислала «5» на опрос
// «оцените обслуживание цифрой от 2 до 5», а Мила поздоровалась и спросила «чем
// могу помочь?». На ЧИСТОЙ цифре ход предрешён — платить за проход провайдера
// не за чем (тот же класс, что closing.js).
//
// Высокая оценка (4–5) ведёт в МОЛЧАНИЕ, а не в благодарность: см. комментарий
// над buildApology. Своей реплики на неё модуль не строит вовсе.
//
// Промпт-правило «ОЦЕНКА ВИЗИТА» никуда не девается и продолжает вести все
// случаи, которые ветка НЕ берёт: смешанный ответ («5, и запишите ещё…»),
// цифра не в ответ на опрос, выключенный флаг AGENT_VISIT_RATING_REPLY.
//
// Условие срабатывания — из ДВУХ половин, и вторая живёт в оркестраторе через
// history.lastOutgoing: последнее исходящее клиники должно быть автоуведомлением
// (authored_by='system') И текстом ОПРОСА (isRatingSurvey ниже). Автора одного
// мало: под 'system' идут и «Вы записаны на прием…», и «Напоминаем о записи…»,
// и касания «Заботы» — голая «2» после напоминания не должна получать в ответ
// «нам очень жаль, что визит вас расстроил».
const { stripAllStamps } = require('./transcript-time');

// Эмодзи и всё, что их собирает: сам пиктограф, VS16 (️ — записан
// ЭСКЕЙПОМ, как в transcript-time.js: сырой символ невидим в редакторе и
// правится вслепую), enclosing keycap (⃣), ZWJ (‍) и модификаторы
// тона кожи. Keycap «5️⃣» после чистки становится обычной «5» — и это верно:
// это ровно та же оценка, только эмодзи-клавишей.
const EMOJI_RE = /\p{Extended_Pictographic}|[️⃣‍]|[\u{1F3FB}-\u{1F3FF}]/gu;

// Маркеры автоопроса об оценке визита. Нужны, чтобы отличить его от прочих
// автоуведомлений того же авторства (запись создана / напоминание о записи /
// касание «Заботы»). Регистр не важен.
// Список НАМЕРЕННО узкий: «балл» и «звёзд» звучат в этой клинике совсем о
// другом («Вам начислено 500 баллов», «сосудистые звёздочки») и давали бы
// ложное срабатывание на живом словаре салона. На боевом тексте опроса PERI
// оба оставшихся маркера срабатывают, ложноотрицательных по проду нет.
const SURVEY_MARKERS = [
  /оцен/i,                       // «оцените», «оценка», «оценить»
  /от\s*2\s*до\s*5/i,            // сама шкала опроса YClients
];

// Текст последнего исходящего — это опрос об оценке визита?
// Без текста (вложение, пустая строка, не-строка) — false: fail-open в LLM.
function isRatingSurvey(text) {
  if (typeof text !== 'string' || !text.trim()) return false;
  return SURVEY_MARKERS.some((re) => re.test(text));
}

// Цифра 2–5 и НИЧЕГО содержательного рядом: эмодзи и пунктуация срезаются,
// любое слово или вторая цифра делают сообщение ответом для LLM. Границы 2–5 —
// из текста самого опроса YClients («цифрой от 2 до 5»).
// Не-строка отвергается ЯВНО, без коэрсии: String([5]) === '5', и массив от
// провайдера/БД молча прошёл бы за оценку (на этом уже обжигались в
// services/care/decision.js, где массив коэрсился в правдоподобный текст).
function parseRating(text) {
  if (typeof text !== 'string') return null;
  const s = stripAllStamps(text)
    .replace(EMOJI_RE, ' ')
    .replace(/[!.,()+\s]+/g, ' ')
    .trim();
  return /^[2-5]$/.test(s) ? Number(s) : null;
}

// messages — транскрипт в формате history.loadTranscript (серии склеены).
// Проверяется ВЕСЬ последний user-блок целиком: строка «5» внутри серии со
// словами — не чистая оценка, её ведёт LLM по правилу промпта.
function detectRating(messages) {
  const list = Array.isArray(messages) ? messages : [];
  const last = list[list.length - 1];
  if (!last || last.role !== 'user') return null;
  return parseRating(last.content);
}

// Своей благодарности за 4–5 тут НЕТ и быть не должно: на такую оценку клиника
// отвечает САМА системным «Спасибо за отличную оценку… За опубликованный отзыв
// дарим 500 бонусов» (по проду — 42 случая из 46, задержка ~17 с). Мила молчит,
// иначе пациент получает две благодарности подряд, а её реплика вдобавок съедает
// повод для сообщения с просьбой об отзыве. Ветка оркестратора возвращает
// silent:true тем же контрактом, что closing.js.

// Извинение за 2–3 + объявление перевода. Слово «администратор» ОБЯЗАТЕЛЬНО:
// по нему диспетчер понимает, что перевод уже объявлен, и не шлёт вторую
// стандартную фразу (admin-hours.HANDOVER_ANNOUNCED_RE — общий признак, тестом
// сверяется с ним, а не с местной копией регулярки).
// adminOff — вне окна присутствия администратора не обещаем скорый ответ
// (та же логика, что admin-hours.handoverText).
function buildApology(opts = {}) {
  const tail = opts.adminOff
    ? 'Передаю ваш диалог администратору клиники — он увидит ваше сообщение и свяжется с вами в начале рабочего дня.'
    : 'Передаю ваш диалог администратору клиники — он свяжется с вами лично, чтобы разобраться.';
  return `Нам очень жаль, что визит вас расстроил — простите нас, пожалуйста. ${tail}`;
}

// EMOJI_RE экспортируется ради promo-interest.js (короткое «+» на акцию): у двух
// коротких предикатов чистка текста обязана быть ОДНОЙ, вторая копия регулярки
// молча разъехалась бы. Флаг /g безопасен: обе стороны зовут только String.replace,
// а он сбрасывает lastIndex.
module.exports = { parseRating, detectRating, isRatingSurvey, buildApology, EMOJI_RE };
