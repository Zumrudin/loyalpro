'use strict';

// ── Короткое согласие на сообщение об акции («+»). Чистый модуль. ────────────
//
// ЗАЧЕМ: правило промпта «СПЕЦПРЕДЛОЖЕНИЕ МЕСЯЦА» требует от модели вызвать
// search_knowledge_base — это ДВА прохода провайдера по ~39k-промпту. Оркестратор
// по этому предикату делает вызов КБ САМ до первого прохода и кладёт статью в
// хвост промпта (спека 2026-08-10-agent-prompt-to-code-offload).
//
// Триггер намеренно УЖЕ промпт-правила: только «+»/«плюс». «Да», «расскажите»,
// «интересно» не триггерят — их пусть разбирает модель (это может быть согласие
// на предложенный слот; вторая половина условия — «последнее исходящее =
// автоуведомление» — проверяется в оркестраторе через history.lastOutgoingAuthor).
const { stripAllStamps } = require('./transcript-time');
// Чистка эмодзи — ОДНА копия на оба коротких предиката («5» на опрос и «+» на
// акцию): keycap, ZWJ, VS16 (эскейпом) и модификаторы тона уже отлажены там.
// Вторая копия регулярки означала бы, что модули молча разъедутся.
const { EMOJI_RE } = require('./visit-rating');

// Правило промпта перечисляет и «да», и «интересно», и «расскажите», но код
// берёт на себя только однозначное «+»: остальное слишком часто относится к
// предыдущей реплике Милы («да» на предложенный слот), и лишний поход в КБ там
// не бесплатен ни по деньгам, ни по смыслу (статья об акции в промпте посреди
// записи сбивает ход).
const PLUS_RE = /^(?:\+{1,3}|плюс)$/i;

// messages — транскрипт в формате history.loadTranscript (серии склеены).
// Проверяется ВЕСЬ последний user-блок целиком: «+» внутри серии со словами —
// не чистое согласие на акцию, такой ход ведёт модель по правилу промпта.
// Не-строка отвергается ЯВНО, без коэрсии: String(['+']) === '+', и массив от
// провайдера/БД молча прошёл бы за согласие (тот же класс, что в
// visit-rating.parseRating и services/care/decision.js).
function isPromoInterest(messages) {
  const list = Array.isArray(messages) ? messages : [];
  const last = list[list.length - 1];
  if (!last || last.role !== 'user' || typeof last.content !== 'string') return false;
  const s = stripAllStamps(last.content)
    .replace(EMOJI_RE, ' ')
    .replace(/[!.,\s]+/g, ' ')
    .trim();
  return PLUS_RE.test(s);
}

module.exports = { isPromoInterest, PLUS_RE };
