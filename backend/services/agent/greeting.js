'use strict';

const { sanitizeName } = require('./sanitize');
const { resolveSalonName } = require('./system-prompt');

// ── Детерминированное приветствие в первом сообщении переписки. ──────────────
// Чистый модуль: ни БД, ни HTTP.
//
// ЗАЧЕМ: инцидент 2026-08-06 (79165370505) — первое в истории обращение
// («Доброе утро! Можете записать меня на эпиляцию … 12.08 на 16.00?»), а Мила
// ответила «Да, на 12 августа в 16:00 есть свободное время…»: ни приветствия,
// ни представления. Блок промпта «ПЕРВОЕ ОБРАЩЕНИЕ» проблему закрыл не до
// конца — на живом пробнике (scripts/agent-greeting-probe.js) ветка известного
// пациента с отказом по времени дала приветствие 1 раз из 3. Промпт-правило
// проигрывает соседним правилам лаконичности («сразу выдавай суть»), поэтому
// приветствие дописывается детерминированно — тот же приём, что с блоком
// «АКТУАЛЬНЫЕ ЗАПИСИ ПАЦИЕНТА»: факт бьёт правило.
//
// Ставится ТОЛЬКО когда мы этому пациенту ещё ни разу не отвечали (firstContact
// в оркестраторе), поэтому лишним оно быть не может по построению.

// Тот же набор форм, что у reply-guard.GREETING_RE (repeat_greeting) —
// намеренная копия смысла, но не импорт: там регэксп с группой захвата под
// значение нарушения, здесь нужен только предикат.
const GREETING_RE = /(здравствуйте|добрый\s+(день|вечер|утро)|доброе\s+утро|приветству)/i;

function hasGreeting(text) {
  return GREETING_RE.test(String(text || ''));
}

// ── Форма приветствия и представления (с 27.10.2026). ───────────────────────
// Решение владельца, ориентир — живые администраторы клиники: приветствие
// отдельной строкой, представление — следующей, суть — после пустой строки.
//
//   Здравствуйте, Полина!🤍
//   Это Мила, виртуальный администратор PERI CLINIC.
//
//   <ответ по делу>
//
// ЗАЧЕМ: прежняя форма склеивала всё в одно предложение («Здравствуйте, Полина!
// Я Мила, виртуальный администратор PERI CLINIC. Спасибо, что подтвердили
// визит…») — замер прода 27.10.2026 нашёл эту «скрепку» в 22 представлениях из
// 23, в том числе перед сочувственными ответами. Сердечко 🤍 ставится, только
// когда реплика не сочувственная (EMPATHY_RE): перед «Мне жаль, что прокол
// гноится» оно читалось бы издёвкой. Формулировка обязана совпадать с образцами
// первого сообщения в system-prompt.js — связь закреплена тестом
// (agent-greeting.test.js, «связь с образцом первого сообщения в промпте»).
// Спека: docs/superpowers/specs/2026-10-27-mila-human-tone-design.md, §4.3.
//
// ── Представление, когда Мила пишет в диалог ВПЕРВЫЕ ────────────────────────
// Инцидент 2026-08-10 (79166524647 и 79295059889): обеим пациенткам раньше
// отвечал ЖИВОЙ администратор, Мила им не писала ни разу — и не представилась.
// Причина: представление жило только в ветке firstContact, а она считается от
// history.hasEverAnswered, где «operator» и до-выкатный NULL идут за «мы уже
// отвечали». Блок промпта «НАЧАЛО НОВОЙ ПЕРЕПИСКИ» вдобавок ПРЯМО запрещает
// представляться «второй раз» — на ложной посылке: первого раза не было.
//
// «Здоровались ли с пациентом вообще» и «писала ли ему САМА Мила» — разные
// вопросы: первый решает приветствие (повторное здравствуйте посреди живого
// разговора неуместно), второй — представление (продублировать его невозможно
// по построению, если Мила ещё ни разу не писала).

// Обе формы: старая «Я Мила…» (реплики модели по памяти, транскрипты до
// 27.10.2026) и новая «Это Мила…» / «На связи Мила…» — иначе представление
// задвоилось бы.
const INTRO_RE = /(я\s+Мила|это\s+Мила|на\s+связи\s+Мила|меня\s+зовут\s+Мила|виртуальн[а-яё]+\s+администратор)/i;

// Сочувствие, извинение, перевод на администратора — без 🤍 в приветственной
// строке: сердечко перед «мне жаль, что прокол гноится» читалось бы издёвкой.
const EMPATHY_RE = /(жаль|сочувств|извин|простите|прошу прощения|передаю)/i;

// Приветствие в самом начале реплики вместе с его знаком препинания и эмодзи:
// представление встаёт отдельной строкой СРАЗУ за ним («Здравствуйте,
// Марина! 👋» ⏎ «Это Мила, …» ⏎⏎ суть), а не абзацем поверх приветствия.
// Эмодзи забирается ВМЕСТЕ с ведущим пробелом и только целой группой: иначе
// `[ \t]*` съедал бы пробел-разделитель и там, где эмодзи нет, — реальная
// реплика «Татьяна, здравствуйте! Понимаю, …» (инцидент 79295059889) склеивалась
// в «…PERI CLINIC.Понимаю» (поймано живым прогоном, не тестами). С 27.10.2026
// остаток после приветствия всё равно начинается с пустой строки, и ведущие
// пробелы/переводы строк остатка срезаются, но граница группы по-прежнему
// решает, где кончается приветственная строка.
const LEADING_GREETING_RE = new RegExp(
  `^\\s*[^.!?\\n]*(?:${GREETING_RE.source.slice(1, -1)})[^.!?\\n]*[.!?]+(?:[ \\t]*\\p{Extended_Pictographic}+)?`,
  'iu');

function hasIntroduction(text) {
  return INTRO_RE.test(String(text || ''));
}

function buildIntroduction(opts = {}) {
  return `Это Мила, виртуальный администратор ${resolveSalonName(opts.salonName)}.`;
}

// Дописывает представление, если его нет ВО ВСЕЙ серии реплик. Форма с
// 27.10.2026 (решение владельца, ориентир — живые администраторы): приветствие
// отдельной строкой, представление — следующей, суть — после пустой строки.
function ensureIntroduction(replies, opts = {}) {
  const list = Array.isArray(replies) ? replies : [];
  if (!list.length) return list;
  if (list.some(hasIntroduction)) return list;
  const out = list.slice();
  const intro = buildIntroduction(opts);
  const lead = out[0].match(LEADING_GREETING_RE);
  if (lead) {
    // Реплика из одного приветствия продолжения не имеет — пустые строки в
    // хвосте пациенту не нужны.
    const rest = out[0].slice(lead[0].length).replace(/^\s+/, '');
    out[0] = `${lead[0].trimEnd()}\n${intro}${rest ? `\n\n${rest}` : ''}`;
  } else {
    out[0] = `${intro}\n\n${out[0]}`;
  }
  return out;
}

// Приветствие по образцу из раздела ИДЕНТИФИКАЦИЯ ПАЦИЕНТА системного промпта
// (та же двухстрочная форма). empathetic — без сердечка (см. EMPATHY_RE).
function buildGreeting(opts = {}) {
  // Имя приходит из карточки YClients — единственное клиент-контролируемое
  // значение здесь. Фильтр тот же, что у промпта: телефон и «Тест 2» вместо
  // имени (11.6% боевых карточек PERI) → обращение без имени.
  const name = sanitizeName(opts.givenName);
  // Название клиники — через общий с промптом резолвер: свой дефолт здесь
  // означал бы, что модель называет клинику одним именем, а дописанное кодом
  // приветствие — другим (в runDialog salonName не передаёт никто).
  const salon = resolveSalonName(opts.salonName);
  const heart = opts.empathetic ? '' : '🤍';
  const hello = `Здравствуйте${name ? `, ${name}` : ''}!${heart}`;
  // withIntro:false — представление в серии уже есть (модель назвалась, но не
  // поздоровалась): дописываем только приветственную строку, иначе «Это Мила…»
  // прозвучало бы дважды.
  if (opts.withIntro === false) return hello;
  return `${hello}\nЭто Мила, виртуальный администратор ${salon}.`;
}

// Дописывает приветствие в НАЧАЛО первой реплики, если во всей серии его нет.
// Серия уходит пациенту отдельными сообщениями, поэтому проверяется вся: своё
// приветствие во второй реплике — тоже приветствие, дублировать его нельзя.
// Сердечко решает сам модуль по всей серии (EMPATHY_RE); явный opts.empathetic
// главнее автоопределения.
function ensureGreeting(replies, opts = {}) {
  const list = Array.isArray(replies) ? replies : [];
  if (!list.length) return list;
  if (list.some(hasGreeting)) return list;
  const out = list.slice();
  const empathetic = opts.empathetic != null ? !!opts.empathetic : EMPATHY_RE.test(list.join('\n'));
  const withIntro = !list.some(hasIntroduction);
  out[0] = `${buildGreeting({ ...opts, empathetic, withIntro })}\n\n${out[0]}`;
  return out;
}

module.exports = {
  hasGreeting, buildGreeting, ensureGreeting,
  hasIntroduction, buildIntroduction, ensureIntroduction, EMPATHY_RE,
};
