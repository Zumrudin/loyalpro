'use strict';

// Вежливое завершение переписки: когда отвечать уже НЕ на что.
//
// ЗАЧЕМ: у Милы нет ветки «промолчать» — ход без реплик диспетчер трактует как
// отказ (эскалация на человека + страховочная фраза), поэтому последнее слово
// всегда оставалось за ней. Инцидент 2026-08-06 (79165370505): после записи она
// попрощалась, дальше пошли «Спасибо!» → «Пожалуйста! Рада была помочь. 🤍» →
// «Благодарю! И Вам» → «Всегда пожалуйста! ✨» — круг закончился только потому,
// что пациентка перестала писать. Промпт-правила тут не работают: молчание для
// модели физически недоступно, она может выбрать лишь текст ответа.
//
// Правило намеренно узкое (молчание должно быть РЕДКИМ и заведомо безопасным):
// молчим, только если И последнее сообщение пациента, И предыдущая реплика Милы
// — чистые формулы вежливости без единого содержательного слова. Отсюда само
// собой получается «один ответ на благодарность разрешён, второй — нет»: своё
// прощание в серии с подтверждением записи («Записала вас!… Хорошего дня!»)
// склеено в ОДИН assistant-блок и чистым уже не считается.
const { stripStamp } = require('./transcript-time');

// Слова, которые могут стоять в чистой формуле вежливости. Всё, чего здесь нет
// (цифры, названия услуг, «перенесите», «во сколько»), делает сообщение
// содержательным — и Мила отвечает как раньше.
const ALLOWED = new Set([
  'спасибо', 'спасибочки', 'спасиб', 'благодарю', 'благодарствую', 'благодарность',
  'пожалуйста', 'взаимно', 'обращайтесь', 'пишите', 'приходите', 'ждем', 'ждала',
  'и', 'а', 'ну', 'вам', 'вас', 'вами', 'тебе', 'тебя', 'тоже', 'также', 'же',
  'очень', 'большое', 'огромное', 'преогромное', 'сердечное', 'всегда', 'конечно',
  'я', 'мы', 'вы', 'был', 'была', 'были', 'рад', 'рада', 'рады', 'помочь',
  'за', 'все', 'это', 'всего', 'всех', 'благ', 'не', 'что', 'если',
  'доброго', 'хорошего', 'наилучшего', 'приятного', 'отличного',
  'дня', 'вечера', 'утра', 'ночи', 'выходных', 'до', 'свидания', 'встречи',
  'скорого', 'пока', 'добра', 'здоровья', 'удачи', 'счастья',
  'ок', 'окей', 'хорошо', 'отлично', 'супер', 'буду', 'будем', 'жду', 'ждем',
]);

// Хотя бы одна явная формула благодарности или прощания. Без неё «Да», «Хорошо»
// и прочие подтверждения остались бы «чистыми» — а это согласие, на которое
// пациент ждёт действия, а не тишины.
const ANCHOR_RE = new RegExp([
  'спасиб', 'благодар', 'пожалуйста', 'взаимн', 'обращайтесь',
  'до свидания', 'до встречи', 'до скорого',
  '\\bпока\\b', '\\bи (вам|вас)\\b', '\\b(вам|вас) тоже\\b',
  'всего (доброго|хорошего|наилучшего)',
  '(хорошего|доброго|приятного|отличного) (дня|вечера|утра|ночи|выходных)',
  '(рад|рада|рады) (была |был |были )?помочь',
].join('|'));

// Метка времени срезается ТЕМ ЖЕ хелпером, что ставит её history.js (правило
// одно и без копий); дальше эмодзи и пунктуация становятся пробелами, а цифры
// намеренно СОХРАНЯЮТСЯ — «Ждём вас 12 августа» обязано остаться содержательным.
function normalize(text) {
  return stripStamp(String(text))
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9]+/g, ' ')
    .trim();
}

function isPureClosing(text) {
  // Вопрос — всегда содержателен, даже если обёрнут в благодарность.
  if (String(text).includes('?')) return false;
  const norm = normalize(text);
  if (!norm) return true;                                  // только эмодзи/знаки
  if (!norm.split(' ').every((w) => ALLOWED.has(w))) return false;
  return ANCHOR_RE.test(norm);
}

// messages — транскрипт в формате history.loadTranscript (роли user/assistant,
// серия сообщений подряд склеена в один блок).
function shouldStaySilent(messages) {
  const list = Array.isArray(messages) ? messages : [];
  if (list.length < 2) return false;
  const last = list[list.length - 1];
  const prev = list[list.length - 2];
  // Своей реплики перед благодарностью нет — отвечаем (в т.ч. первое обращение).
  if (!last || last.role !== 'user' || !prev || prev.role !== 'assistant') return false;
  // Реплика администратора чистой формулой не будет никогда: маркер
  // OPERATOR_MARK состоит из слов вне ALLOWED — это закреплено тестом.
  return isPureClosing(prev.content) && isPureClosing(last.content);
}

module.exports = { shouldStaySilent };
