function collect(...blocks) {
  const set = new Set();
  for (const block of blocks) {
    for (const w of block.split(/\s+/)) {
      const s = w.trim().toLowerCase().replace(/ё/g, 'е');
      // Латиница/опечатки в исходных блоках молча не проглатываем — в словарь
      // попадают только кириллические слова из 2+ букв.
      if (/^[а-я][а-я-]+$/.test(s)) set.add(s);
    }
  }
  return set;
}

const BASE_GIVEN_NAMES = collect(FEMALE_RU, MALE_RU, DIMINUTIVES, REGIONAL);

module.exports = { BASE_GIVEN_NAMES };
