'use strict';
const router=require('express').Router();
const {auth,requireRole}=require('../middleware/auth');
const service=require('../services/service-catalog');
const reconcile=require('../services/service-catalog-reconcile');
const economics=require('../services/economics/report');
const {JournalError,positiveId}=require('../services/journal/model');
router.use(auth,requireRole('owner','admin'));
router.use((req,res,next)=>{res.set('Cache-Control','no-store');next();});
const handle=fn=>async(req,res)=>{try{res.json(await fn(req));}catch(e){res.status(e instanceof JournalError?e.status:502).json({error:e instanceof JournalError?e.message:'Не удалось выполнить операцию с каталогом. Попробуйте ещё раз.'});}};
const mutate=fn=>async req=>{const result=await fn(req);economics.invalidate(req.user.salonId);require('../services/agent/price-list-data').invalidate(req.user.salonId);return result;};
router.get('/',handle(req=>service.list(req.user.salonId)));
router.post('/import',handle(mutate(req=>service.importYclients(req.user.salonId))));
router.post('/reconcile/preview',handle(req=>reconcile.preview(req.user.salonId)));
router.post('/reconcile/:runId/apply',handle(mutate(req=>reconcile.apply(req.user.salonId,req.params.runId))));
router.post('/categories',handle(mutate(req=>service.saveCategory(req.user.salonId,null,req.body))));
router.put('/categories/:id',handle(mutate(req=>service.saveCategory(req.user.salonId,positiveId(req.params.id),req.body))));
router.post('/services',handle(mutate(req=>service.saveService(req.user.salonId,null,req.body))));
router.put('/services/:id',handle(mutate(req=>service.saveService(req.user.salonId,positiveId(req.params.id),req.body))));
router.use(require('./service-category-photos'));
module.exports=router;
