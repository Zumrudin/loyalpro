'use strict';
// Готовый текст касания (text_mode=strict) рендерит КОД, а не модель
// (2026-09-28): модель его не видит и не может ни отказать из-за содержания
// (на проде 3 эскалации «готовый текст содержит медицинскую рекомендацию» на
// тексте, который написал сам салон), ни переписать.
const { renderStrictText } = require('./services/care/strict-text');

describe('renderStrictText', () => {
  test('подставляет имя вместо [Имя]', () => {
    expect(renderStrictText('[Имя], здравствуйте! Как самочувствие?', 'Анна'))
      .toBe('Анна, здравствуйте! Как самочувствие?');
  });
  test('плейсхолдер в любом регистре и в фигурных скобках', () => {
    expect(renderStrictText('[имя], добрый день!', 'Анна')).toBe('Анна, добрый день!');
    expect(renderStrictText('{Имя}, добрый день!', 'Анна')).toBe('Анна, добрый день!');
  });
  test('имени нет → плейсхолдер с запятой убирается, следующее слово с заглавной', () => {
    expect(renderStrictText('[Имя], здравствуйте! Вас беспокоит отдел заботы.', null))
      .toBe('Здравствуйте! Вас беспокоит отдел заботы.');
  });
  test('имени нет, плейсхолдер в середине → просто убирается', () => {
    expect(renderStrictText('Добрый день, [Имя]! Как вы?', null)).toBe('Добрый день! Как вы?');
  });
  test('плейсхолдера нет → текст как есть, имя не дописывается', () => {
    expect(renderStrictText('Добрый день! Как самочувствие?', 'Анна')).toBe('Добрый день! Как самочувствие?');
  });
  test('переводы строк шаблона сохраняются (салон форматирует абзацами)', () => {
    expect(renderStrictText('[Имя], здравствуйте!\n\nКак самочувствие?', 'Анна'))
      .toBe('Анна, здравствуйте!\n\nКак самочувствие?');
  });
  test('bidi/контрольные символы вычищаются, как у текста модели', () => {
    expect(renderStrictText('Скидка 50‮%', 'Анна')).toBe('Скидка 50%');
  });
  test('пустой/не строка/длиннее 1500 символов → null (fail-safe, не отправка)', () => {
    expect(renderStrictText('', 'Анна')).toBeNull();
    expect(renderStrictText(null, 'Анна')).toBeNull();
    expect(renderStrictText(['a'], 'Анна')).toBeNull();
    expect(renderStrictText('а'.repeat(1501), 'Анна')).toBeNull();
    expect(renderStrictText('а'.repeat(1500), 'Анна')).toHaveLength(1500);
  });
  test('имя с мусором в шаблон не проходит как есть — только словесное имя', () => {
    // имя уже прошло resolveGivenName у вызывающего; здесь страховка от
    // не-строки, чтобы «[object Object], здравствуйте» не ушло пациенту.
    expect(renderStrictText('[Имя], привет!', { a: 1 })).toBe('Привет!');
  });
});
