'use strict';

const { shouldStaySilent } = require('./services/agent/closing');

const u = (content) => ({ role: 'user', content });
const a = (content) => ({ role: 'assistant', content });

// Хвост реальной переписки 79165370505 от 06.08.2026 (инцидент «взаимные
// благодарности по кругу»): Мила уже попрощалась, дальше шли только «спасибо».
describe('shouldStaySilent', () => {
  test('чистая благодарность после чистого прощания Милы → молчим', () => {
    expect(shouldStaySilent([
      u('Спасибо!'),
      a('Пожалуйста! Рада была помочь. 🤍'),
      u('Благодарю!И Вам🌹'),
    ])).toBe(true);
  });

  test('ПЕРВАЯ благодарность после содержательной реплики → отвечаем', () => {
    // Серия Милы склеена в один блок: подтверждение записи + прощание.
    expect(shouldStaySilent([
      u('🌹'),
      a('Записала вас! 🌸 Ждём вас 12 августа в 16:00 к косметологу Татьяне.\nБыла рада помочь! Хорошего дня! ✨'),
      u('Спасибо!'),
    ])).toBe(false);
  });

  test('благодарность с вопросом → отвечаем', () => {
    expect(shouldStaySilent([
      a('Всегда пожалуйста! ✨'),
      u('Спасибо! А во сколько лучше прийти?'),
    ])).toBe(false);
  });

  test('благодарность с содержательным довеском без вопросительного знака → отвечаем', () => {
    expect(shouldStaySilent([
      a('Всегда пожалуйста! ✨'),
      u('Спасибо. И перенесите меня на 17:00'),
    ])).toBe(false);
  });

  test('серия пациента: благодарность + новый вопрос → отвечаем', () => {
    expect(shouldStaySilent([
      a('Рада была помочь! Хорошего дня!'),
      u('Спасибо!\nА бонусы у меня есть?'),
    ])).toBe(false);
  });

  test('эмодзи-реакция после чистого прощания → молчим', () => {
    expect(shouldStaySilent([
      a('Всегда пожалуйста! ✨'),
      u('🌹'),
    ])).toBe(true);
  });

  test('«Да» после прощания — подтверждение, а не благодарность → отвечаем', () => {
    expect(shouldStaySilent([
      a('Всегда пожалуйста! ✨'),
      u('Да'),
    ])).toBe(false);
  });

  test('метки времени в транскрипте распознаванию не мешают', () => {
    expect(shouldStaySilent([
      a('[06.08 11:31] Пожалуйста! Рада была помочь. 🤍'),
      u('[06.08 11:31] Благодарю!'),
    ])).toBe(true);
  });

  test('последняя реплика написана администратором → отвечаем (не наше прощание)', () => {
    expect(shouldStaySilent([
      a('[сообщение администратора клиники] Пожалуйста!'),
      u('Спасибо!'),
    ])).toBe(false);
  });

  test('благодарность в самом начале, своих реплик ещё не было → отвечаем', () => {
    expect(shouldStaySilent([u('Спасибо!')])).toBe(false);
  });

  test('транскрипт кончается не пациентом → отвечаем', () => {
    expect(shouldStaySilent([u('Спасибо!'), a('Всегда пожалуйста!')])).toBe(false);
  });

  test('пустой транскрипт и мусор на входе → отвечаем (fail-open)', () => {
    expect(shouldStaySilent([])).toBe(false);
    expect(shouldStaySilent(null)).toBe(false);
    expect(shouldStaySilent(undefined)).toBe(false);
  });

  test('длинное благодарственное сообщение с деталями → отвечаем', () => {
    expect(shouldStaySilent([
      a('Всегда пожалуйста! ✨'),
      u('Спасибо большое, всё очень понравилось, но подскажите — можно ли записаться ещё и на чистку в этом месяце'),
    ])).toBe(false);
  });

  test('прощание пациента без благодарности («до свидания») → тоже молчим', () => {
    expect(shouldStaySilent([
      a('Всегда пожалуйста! ✨'),
      u('До свидания!'),
    ])).toBe(true);
  });

  // Точный вид блоков из history.loadTranscript: метка времени у КАЖДОЙ строки,
  // серия исходящих склеена в один assistant-блок. Ровно на этой склейке и
  // держится «один ответ на благодарность разрешён, второй — нет».
  test('реальный хвост 79165370505 от 06.08: первый «спасибо» — ответ, второй — молчание', () => {
    const confirmation = {
      role: 'assistant',
      content: '[06.08 11:30] Записала вас! 🌸 Ждём вас 12 августа в **16:00** на комплекс '
        + '«Тотальное бикини и подмышки» к косметологу-эстетисту Татьяне.\n'
        + '[06.08 11:30] Была рада помочь! Хорошего дня! ✨',
    };
    const afterFirstThanks = [u('[06.08 11:29] 🌹'), confirmation, u('[06.08 11:30] Спасибо!')];
    expect(shouldStaySilent(afterFirstThanks)).toBe(false);

    expect(shouldStaySilent([
      ...afterFirstThanks,
      a('[06.08 11:31] Пожалуйста! Рада была помочь. 🤍'),
      u('[06.08 11:31] Благодарю!И Вам🌹'),
    ])).toBe(true);
  });

  test('содержательная реплика Милы БЕЗ прощания → на благодарность отвечаем', () => {
    expect(shouldStaySilent([
      a('Стоимость процедуры — 5000 ₽.'),
      u('Спасибо!'),
    ])).toBe(false);
  });
});
