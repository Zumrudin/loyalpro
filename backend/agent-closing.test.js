'use strict';

const { shouldStaySilent, isPureClosing, isAcknowledgment, isClosingReply } = require('./services/agent/closing');

const u = (content) => ({ role: 'user', content });
const a = (content) => ({ role: 'assistant', content });

// Хвост реальной переписки 79165370505 от 06.08.2026 (инцидент «взаимные
// благодарности по кругу»): Мила уже попрощалась, дальше шли только «спасибо».
describe('shouldStaySilent', () => {
  test('чистая благодарность после чистого прощания Милы → молчим', () => {
    expect(shouldStaySilent([
      u('Спасибо!'),
      a('Пожалуйста! Рада была помочь. 🤍'),
      u('Благодарю!И Вам🌹'),
    ])).toBe(true);
  });

  test('ПЕРВАЯ благодарность после содержательной реплики → отвечаем', () => {
    // Серия Милы склеена в один блок: подтверждение записи + прощание.
    expect(shouldStaySilent([
      u('🌹'),
      a('Записала вас! 🌸 Ждём вас 12 августа в 16:00 к косметологу Татьяне.\nБыла рада помочь! Хорошего дня! ✨'),
      u('Спасибо!'),
    ])).toBe(false);
  });

  test('благодарность с вопросом → отвечаем', () => {
    expect(shouldStaySilent([
      a('Всегда пожалуйста! ✨'),
      u('Спасибо! А во сколько лучше прийти?'),
    ])).toBe(false);
  });

  test('благодарность с содержательным довеском без вопросительного знака → отвечаем', () => {
    expect(shouldStaySilent([
      a('Всегда пожалуйста! ✨'),
      u('Спасибо. И перенесите меня на 17:00'),
    ])).toBe(false);
  });

  test('серия пациента: благодарность + новый вопрос → отвечаем', () => {
    expect(shouldStaySilent([
      a('Рада была помочь! Хорошего дня!'),
      u('Спасибо!\nА бонусы у меня есть?'),
    ])).toBe(false);
  });

  test('эмодзи-реакция после чистого прощания → молчим', () => {
    expect(shouldStaySilent([
      a('Всегда пожалуйста! ✨'),
      u('🌹'),
    ])).toBe(true);
  });

  test('«Да» после прощания — подтверждение, а не благодарность → отвечаем', () => {
    expect(shouldStaySilent([
      a('Всегда пожалуйста! ✨'),
      u('Да'),
    ])).toBe(false);
  });

  test('метки времени в транскрипте распознаванию не мешают', () => {
    expect(shouldStaySilent([
      a('[06.08 11:31] Пожалуйста! Рада была помочь. 🤍'),
      u('[06.08 11:31] Благодарю!'),
    ])).toBe(true);
  });

  test('последняя реплика написана администратором → отвечаем (не наше прощание)', () => {
    expect(shouldStaySilent([
      a('[сообщение администратора клиники] Пожалуйста!'),
      u('Спасибо!'),
    ])).toBe(false);
  });

  test('благодарность в самом начале, своих реплик ещё не было → отвечаем', () => {
    expect(shouldStaySilent([u('Спасибо!')])).toBe(false);
  });

  test('транскрипт кончается не пациентом → отвечаем', () => {
    expect(shouldStaySilent([u('Спасибо!'), a('Всегда пожалуйста!')])).toBe(false);
  });

  test('пустой транскрипт и мусор на входе → отвечаем (fail-open)', () => {
    expect(shouldStaySilent([])).toBe(false);
    expect(shouldStaySilent(null)).toBe(false);
    expect(shouldStaySilent(undefined)).toBe(false);
  });

  test('длинное благодарственное сообщение с деталями → отвечаем', () => {
    expect(shouldStaySilent([
      a('Всегда пожалуйста! ✨'),
      u('Спасибо большое, всё очень понравилось, но подскажите — можно ли записаться ещё и на чистку в этом месяце'),
    ])).toBe(false);
  });

  test('прощание пациента без благодарности («до свидания») → тоже молчим', () => {
    expect(shouldStaySilent([
      a('Всегда пожалуйста! ✨'),
      u('До свидания!'),
    ])).toBe(true);
  });

  // Точный вид блоков из history.loadTranscript: метка времени у КАЖДОЙ строки,
  // серия исходящих склеена в один assistant-блок. Ровно на этой склейке и
  // держится «один ответ на благодарность разрешён, второй — нет».
  test('реальный хвост 79165370505 от 06.08: первый «спасибо» — ответ, второй — молчание', () => {
    const confirmation = {
      role: 'assistant',
      content: '[06.08 11:30] Записала вас! 🌸 Ждём вас 12 августа в **16:00** на комплекс '
        + '«Тотальное бикини и подмышки» к косметологу-эстетисту Татьяне.\n'
        + '[06.08 11:30] Была рада помочь! Хорошего дня! ✨',
    };
    const afterFirstThanks = [u('[06.08 11:29] 🌹'), confirmation, u('[06.08 11:30] Спасибо!')];
    expect(shouldStaySilent(afterFirstThanks)).toBe(false);

    expect(shouldStaySilent([
      ...afterFirstThanks,
      a('[06.08 11:31] Пожалуйста! Рада была помочь. 🤍'),
      u('[06.08 11:31] Благодарю!И Вам🌹'),
    ])).toBe(true);
  });

  test('содержательная реплика Милы БЕЗ прощания → на благодарность отвечаем', () => {
    expect(shouldStaySilent([
      a('Стоимость процедуры — 5000 ₽.'),
      u('Спасибо!'),
    ])).toBe(false);
  });

  test('«И вам!» после чистого прощания Милы → молчим', () => {
    expect(shouldStaySilent([
      a('Всегда пожалуйста! Хорошего дня ✨'),
      u('И вам!'),
    ])).toBe(true);
  });
});

// `\b` в JS-регэкспе понимает только латиницу, поэтому якоря «пока», «и вам»
// и «вам тоже» не срабатывали никогда (найдено 07.11.2026 при разборе 79292633336).
describe('isPureClosing: прощания на кириллице', () => {
  test.each(['Пока!', 'Пока-пока 👋', 'И вам!', 'И вас тоже', 'Вам тоже', 'вам тоже)'])(
    '«%s» → чистая вежливость', (text) => {
      expect(isPureClosing(text)).toBe(true);
    });

  test('без якоря и с содержательным словом — по-прежнему нет', () => {
    expect(isPureClosing('Ок')).toBe(false);
    expect(isPureClosing('Пока не знаю')).toBe(false);
  });
});

// Голое подтверждение пациента. Нужно только решению о переводе при закрытии
// окна расписания (window-handover.js) и только вместе с isClosingReply.
describe('isAcknowledgment', () => {
  test.each(['Ок', 'ок)', 'Окей', 'ok', 'Хорошо', 'Понятно', 'Понятно. Спасибо', 'Ясно',
    'Принято', 'Отлично!', 'Супер', 'Хорошо, буду', 'Ок 👍', 'Договорились', 'Ладно', 'Все понятно'])(
    '«%s» → подтверждение', (text) => {
      expect(isAcknowledgment(text)).toBe(true);
    });

  // «Да» — главное слово согласия: на проде 14 из 16 коротких ответов на вопрос
  // Милы были именно «да» (замер 07.11.2026), поэтому подтверждением не считается.
  test.each(['Да', 'Да да', 'Давайте', 'Хорошо, давайте', 'Не понятно', 'Ок, а сколько стоит?',
    'Хорошо, перенесите на 12', '👍', '', '   '])(
    '«%s» → не подтверждение', (text) => {
      expect(isAcknowledgment(text)).toBe(false);
    });

  test('не строка → false', () => {
    expect(isAcknowledgment(null)).toBe(false);
    expect(isAcknowledgment(undefined)).toBe(false);
    expect(isAcknowledgment(['ок'])).toBe(false);
  });
});

// Реплики Милы с прода. «Закрыла разговор» = нет вопроса И есть прощание или
// отчёт о сделанном: на «Ок» после такой реплики отвечать некому и незачем.
describe('isClosingReply', () => {
  test.each([
    // 79292633336, 07.11.2026 — сам инцидент
    'Татьяна, записала Вас на фотоомоложение лица к Астемиру Алексеевичу в четверг, 12 ноября, в 10:30. До встречи!',
    // подтверждения записи без прощания — так кончаются 10 из 29 на проде
    'Сюзанна, записала Вас на лазерную эпиляцию шеи к Татьяне сегодня, в понедельник, 28 сентября, на **18:30**.',
    'Анна, перенесла Вашу запись на кольца Венеры к Пери Исамудиновне на воскресенье, 4 октября, **16:30**.',
    'Поняла вас, Татьяна. Отменила вашу запись на HELEO4 на завтра. Ваша запись на 25 сентября в 11:00 остаётся в силе. 🤍',
    'Если появятся вопросы — напишите, будем рады помочь. Хорошего дня!',
    'Если появятся вопросы, пишите, я на связи 🤍',
  ])('«%s» → закрыла', (text) => {
    expect(isClosingReply(text)).toBe(true);
  });

  test.each([
    'В четверг, 12 ноября, в 10:30 время свободно. Записать Вас на фотоомоложение лица к Астемиру Алексеевичу?',
    // 79186038923, 01.10.2026: вопроса нет, но «Да» пациентки — согласие продолжить
    'Екатерина, возвращаюсь к вашей записи к Юлии на 3 октября в 19:30. Если она ещё актуальна, напишите, пожалуйста, и мы продолжим оформление.',
    'Записала Вас на 10:30. До встречи! Хотите, добавлю ещё консультацию?',
    'К сожалению, не записала Вас: время уже занято. Могу предложить 11:00.',
    'Сапият, я проверила информацию по вашему визиту 4 августа. Вам вводили препарат Stylage Special Lips в объеме 1 мл. 🤍',
    'Могу записать Вас на 10:30.',
    '',
  ])('«%s» → не закрыла', (text) => {
    expect(isClosingReply(text)).toBe(false);
  });

  test('не строка → false', () => {
    expect(isClosingReply(null)).toBe(false);
    expect(isClosingReply(undefined)).toBe(false);
  });
});
